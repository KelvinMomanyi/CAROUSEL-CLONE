import { createHash } from "node:crypto";
import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

// One version for the directory preserves relative CSS/font/image references.
export function preparePreviewAssets(root = process.cwd()) {
  const source = join(root, "extensions/carousel-sliders/assets");
  const files = readdirSync(source).sort();
  const hash = createHash("sha256");
  for (const file of files) hash.update(file).update(readFileSync(join(source, file)));
  const base = `/preview-assets/${hash.digest("hex").slice(0, 20)}`;
  const destination = join(root, "public", base.slice(1));
  mkdirSync(destination, { recursive: true });
  for (const file of files) copyFileSync(join(source, file), join(destination, file));
  const generated = join(root, "app/generated");
  mkdirSync(generated, { recursive: true });
  writeFileSync(join(generated, "preview-assets.server.js"),
    `// Generated by scripts/preview-assets.mjs.\nexport const previewAssetBase = ${JSON.stringify(base)};\n`);
  return base;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  preparePreviewAssets();
}
